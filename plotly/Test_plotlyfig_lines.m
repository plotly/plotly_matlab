            for i = 1:6
                tc.verifyEqualStructs(p.data{i}, struct( ...
                    "type", "scatter", ...
                    "xaxis", sprintf("x%d", i), ...
                    "yaxis", sprintf("y%d", i), ...
                    "visible", true, ...
                    "name", '', ...
                    "mode", 'markers', ...
