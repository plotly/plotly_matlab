            x = 1:10;
            y = rand(10,1);
            stem(x, y, 'filled');

            p = plotlyfig(fig,"visible","off");

            if is_octave()
                % Octave's stem handler renders the y=0 baseline as a
                % second trace and uses LineWidth 0.5 with row vectors
