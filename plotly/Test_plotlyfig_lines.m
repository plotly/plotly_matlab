                    "y", scatterXY{i,2}, ...
                    "line", struct(), ...
                    "marker", struct( ...
                        "size", 3, ...
                        "symbol", "circle", ...
                        "maxdisplayed", 7, ...
                        "line", struct( ...
                            "width", 0.5 ...
                        ), ...
                        "color", PlotlyTestCase.AnyColorString() ...
                    ), ...
                    "showlegend", false ...
                ), 'AbsTol', 1e-15);
            end
            barY = {[2 4]; [4 2]; [4 2]};
            for i = 1:3
                tc.verifyEqualStructs(p.data{i+6}, struct( ...
                    "xaxis", sprintf("x%d", i+6), ...
