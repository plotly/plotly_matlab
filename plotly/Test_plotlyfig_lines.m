        function testPlotmatrixData(tc)
            fig = figure("Visible","off");
            columns = [ ...
                0.67  0.77  0.42;
                0.43  0.70  0.66;
                0.45  0.13  0.72;
                0.61  0.13  0.53;
                0.06  0.09  0.11;
                0.32  0.01  0.63];
            plotmatrix(columns);

            p = plotlyfig(fig,"visible","off");

            if is_octave()
                tc.verifyNumElements(p.data, 9); % 3x3 matrix, no parent plot
                for i = 1:9
                    d = p.data{i};
                    tc.verifyEqual(d.xaxis, sprintf("x%d", i));
                    tc.verifyEqual(d.yaxis, sprintf("y%d", i));
                    if ismember(i, [1 5 9])
                        tc.verifyEqual(d.type, "bar");
                    else
                        tc.verifyEqual(d.type, "scatter");
                        tc.verifyEqual(d.mode, "markers");
                    end
                end
                try close(); catch; end
                return
            end

            % MATLAB: 9 traces with no parent plot; the 6 off-diagonal
            % scatters come first, then the 3 diagonal histograms as bars
            tc.verifyNumElements(p.data, 9);
            scatterXY = { ...
                [0.77 0.7 0.13 0.13 0.09 0.01], [0.42 0.66 0.72 0.53 0.11 0.63]; ...
                [0.67 0.43 0.45 0.61 0.06 0.32], [0.42 0.66 0.72 0.53 0.11 0.63]; ...
                [0.42 0.66 0.72 0.53 0.11 0.63], [0.77 0.7 0.13 0.13 0.09 0.01]; ...
                [0.67 0.43 0.45 0.61 0.06 0.32], [0.77 0.7 0.13 0.13 0.09 0.01]; ...
                [0.42 0.66 0.72 0.53 0.11 0.63], [0.67 0.43 0.45 0.61 0.06 0.32]; ...
                [0.77 0.7 0.13 0.13 0.09 0.01], [0.67 0.43 0.45 0.61 0.06 0.32] ...
