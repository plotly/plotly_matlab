        function testLogLogPlot(tc)
            fig = figure("Visible","off");
            zeta = 0.5; % damping factor
            color = "r";
            w = logspace(-1, 1, 1000); % values equally spaced logarithmically
            a = w.^2 - 1;
            b = 2*w*zeta;
            gain = sqrt(1./(a.^2 + b.^2));
            loglog(w, gain, color=color);
            axis([0.1 10 0.01 100]);

            p = plotlyfig(fig,"visible","off");

            tc.verifyNumElements(p.data, 1);
            tc.verifyEqual(p.data{1}, struct( ...
                "type", "scatter", ...
                "xaxis", "x1", ...
                "yaxis", "y1", ...
                "name", '', ...
                "mode", 'lines', ...
                "x", w, ...
                "y", gain, ...
                "marker", struct( ...
                    "size", 3.6, ...
                    "line", struct( ...
                        "width", 0.5 ...
                    ), ...
                    "color", "rgb(255,0,0)" ...
                ), ...
                "line", struct( ...
                    "color", "rgb(255,0,0)", ...
                    "width", 0.5, ...
                    "dash", "solid" ...
                ), ...
                "visible", true, ...
                "showlegend", false ...
            ), 'AbsTol', 1e-15);
            try close(); catch; end
        end

