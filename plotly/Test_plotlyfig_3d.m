        function testScatter3DPlotData(tc)
            fig = figure("Visible","off");
            [X,Y,Z] = sphere(16);
            x = [0.5*X(:); 0.75*X(:); X(:)]';
            y = [0.5*Y(:); 0.75*Y(:); Y(:)]';
            z = [0.5*Z(:); 0.75*Z(:); Z(:)]';
            scatter3(x,y,z);

            p = plotlyfig(fig,"visible","off");

            if is_octave()
                xData = x(:);
                yData = y(:);
                zData = z(:);
            else
                xData = x;
                yData = y;
                zData = z;
            end

            tc.verifyNumElements(p.data, 1);
            tc.verifyEqualStructs(p.data{1}, struct( ...
                "type", "scatter3d", ...
                "scene", "scene1", ...
                "mode", "markers", ...
                "visible", true, ...
                "name", '', ...
                "x", xData, ...
                "y", yData, ...
                "z", zData, ...
                "marker", struct( ...
                    "sizeref", 1, ...
                    "sizemode", "area", ...
                    "size", 72 * ones(size(xData)), ...
                    "line", struct( ...
                        "width", 0.7500, ...
                        "color", PlotlyTestCase.AnyColorString() ...
                    ), ...
                    "symbol", "circle", ...
                    "color", "rgba(0,0,0,0)", ...
                    "opacity", 1 ...
                ), ...
                "showlegend", false ...
            ));
            try close(); catch; end
        end

        function testSurfacePlotData(tc)
            fig = figure("Visible","off");
            points = linspace(-2, 2, 40);
            [x, y] = meshgrid(points, points);
            z = 2./exp((x-0.5).^2+y.^2)-2./exp((x+0.5).^2+y.^2);
            surf(x, y, z)

            p = plotlyfig(fig,"visible","off");

            % both engines: surf emits a scene-based surface plus a
            % scatter3d wireframe trace
            tc.verifyNumElements(p.data, 2);
            tc.verifyEqual(p.data{1}.type, "surface");
            tc.verifyEqual(p.data{1}.scene, "scene1");
            tc.verifyEqual(p.data{1}.contours.x.start, -2);
            tc.verifyEqual(p.data{1}.contours.x.end, 2);
            tc.verifyEqual(p.data{1}.contours.y.start, -2);
            tc.verifyEqual(p.data{1}.contours.y.end, 2);
            tc.verifyEqual(p.data{2}.type, "scatter3d");
            tc.verifyEqual(p.data{2}.mode, "lines");
            tc.verifyEqual(p.data{2}.scene, "scene1");
            try close(); catch; end
        end

