        function testStem3PlotData(tc)
            % stem3 becomes a single lines+markers scatter3d trace with
            % each stem laid out as a (base, tip, NaN) triple.
            fig = figure("Visible","off");
            t = 0:0.2:6*pi;
            x = cos(t);
            y = sin(t);
            z = t;
            stem3(x, y, z);

            p = plotlyfig(fig,"visible","off");

            tc.verifyNumElements(p.data, 1);
            expected = struct( ...
                "type", "scatter3d", ...
                "scene", "scene1", ...
                "visible", true, ...
                "name", '', ...
                "mode", 'lines+markers', ...
                "x", reshape([x; x; nan(1,length(x))], [], 1), ...
                "y", reshape([y; y; nan(1,length(y))], [], 1), ...
                "z", reshape([zeros(1,length(z)); z; nan(1,length(z))], [], 1), ...
                "line", struct( ...
                    "color", PlotlyTestCase.AnyColorString(), ...
                    "width", 1, ...
                    "dash", "solid" ...
                ), ...
                "marker", struct( ...
                    "size", 2.16, ...
                    "symbol", "circle", ...
                    "line", struct( ...
                        "width", 1, ...
                        "color", PlotlyTestCase.Any() ...
                    ), ...
                    "color", PlotlyTestCase.Any() ...
                ), ...
                "showlegend", false ...
            );
            if is_octave()
                % MATLAB's updateStem doubles the widths and emits
                % column vectors; Octave's updateStemseries does not
                expected.x = reshape([x; x; nan(1,length(x))], 1, []);
                expected.y = reshape([y; y; nan(1,length(y))], 1, []);
                expected.z = reshape([zeros(1,length(z)); z; nan(1,length(z))], 1, []);
                expected.line.width = 0.5;
                expected.marker.size = 3.6;
                expected.marker.line.width = 0.5;
            end
            tc.verifyEqualStructs(p.data{1}, expected, 'AbsTol', 1e-15);
            try close(); catch; end
        end

