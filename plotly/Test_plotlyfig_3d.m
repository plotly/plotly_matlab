        function testBar3PlotData(tc)
            % bar3 emits one mesh3d face trace plus per-bar edge
            % traces on scene1. MATLAB's bar3 draws a surface object
            % that converts to a plain surface trace instead.
            fig = figure("Visible","off");
            bar3(peaks(5)/10);

            p = plotlyfig(fig,"visible","off");

            expected = struct( ...
                "type", "surface", ...
                "scene", "scene1", ...
                "visible", true, ...
                "name", '', ...
                "x", PlotlyTestCase.Any(), ...
                "y", PlotlyTestCase.Any(), ...
                "z", PlotlyTestCase.Any(), ...
                "surfacecolor", PlotlyTestCase.Any(), ...
                "cmax", PlotlyTestCase.Any(), ...
                "cmin", PlotlyTestCase.Any(), ...
                "colorscale", PlotlyTestCase.Any(), ...
                "contours", PlotlyTestCase.Any(), ...
                "lighting", PlotlyTestCase.Any(), ...
                "opacity", PlotlyTestCase.Any(), ...
                "showscale", PlotlyTestCase.Any(), ...
                "showlegend", true ...
            );
            if is_octave()
                % Octave's bar3 patches convert to a mesh3d face
                % trace with per-bar edge traces
                expected = rmfield(expected, ...
                    {'surfacecolor', 'contours', 'lighting', 'opacity'});
                expected.xaxis = "x1";
                expected.yaxis = "y1";
                expected.type = "mesh3d";
                expected.i = PlotlyTestCase.Any();
                expected.j = PlotlyTestCase.Any();
                expected.k = PlotlyTestCase.Any();
                expected.color = PlotlyTestCase.AnyColorString();
                expected.intensity = PlotlyTestCase.Any();
                expected.showscale = false;
                expected.showlegend = false;
            end
            tc.verifyEqualStructs(p.data{1}, expected, 'AbsTol', 1e-15);
            if is_octave()
                tc.verifyNumElements(p.data, 151);
                tc.verifyEqual(size(p.data{1}.i), [300 1]);
                tc.verifyEqual(p.data{2}.type, "scatter3d");
                tc.verifyEqual(p.data{end}.type, "scatter3d");
            end
            try close(); catch; end
        end

