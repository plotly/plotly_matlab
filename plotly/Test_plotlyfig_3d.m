                "scene", "scene1", ...
                "type", "scatter3d", ...
                "mode", "lines", ...
                "line", struct( ...
                    "color", "rgb(217,217,217)", ...
                    "width", 1.5, ...
                    "dash", "solid" ...
                ), ...
                "name", '{sin}({x}) {cos}({y})', ...
