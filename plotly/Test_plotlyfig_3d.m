        function testRibbonPlotData(tc)
            fig = figure("Visible","off");
            n = 50;
            x = linspace(0,4*pi,n);
            y = [sin(x); sin(x)+0.5; sin(x)+1]';
            ribbon(x,y);

            p = plotlyfig(fig,"visible","off");

            % both engines: ribbon emits 3 scene-based surfaces plus
            % 3 scatter3d wireframe traces
            tc.verifyNumElements(p.data, 6);
            for i = 1:3
                tc.verifyEqual(p.data{i}.type, "surface");
                tc.verifyEqual(p.data{i}.scene, "scene1");
            end
            for i = 4:6
                tc.verifyEqual(p.data{i}.type, "scatter3d");
                tc.verifyEqual(p.data{i}.mode, "lines");
                tc.verifyEqual(p.data{i}.scene, "scene1");
            end
            try close(); catch; end
        end

        function testFunctionSurfacePlotData(tc)
            if is_octave()
                return % The `fsurf` function is not yet implemented in Octave.
            end
