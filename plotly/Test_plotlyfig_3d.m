        end

        function testIsosurfacePlotData(tc)
            fig = figure("Visible","off");
            [X,Y,Z] = meshgrid(linspace(-1,1,20),linspace(-1,1,20),linspace(-1,1,20));
            V = X.^2 + Y.^2 + Z.^2;
            isosurface(X,Y,Z,V,0.5);

            plotData = get(get(fig, 'children'), 'children');
            plotData = plotData(2);
            p = plotlyfig(fig,"visible","off","treatAs",'isosurface');

            tc.verifyNumElements(p.data, 1);
            vertices = get(plotData, 'Vertices');
            faces = get(plotData, 'Faces');
            expected = struct( ...
                "type", "mesh3d", ...
                "name", '', ...
                "showscale", false, ...
                "x", vertices(:,1), ...
                "y", vertices(:,2), ...
                "z", vertices(:,3), ...
                "i", faces(:,1) - 1, ...
                "j", faces(:,2) - 1, ...
                "k", faces(:,3) - 1, ...
                "color", "rgb(16,190,186)", ...
                "lighting", struct( ...
                    "diffuse", 0.6, ...
                    "ambient", 0.3, ...
                    "specular", 0.9, ...
                    "roughness", 0.2, ...
                    "fresnel", 0.5, ...
                    "vertexnormalsepsilon", 1e-12, ...
                    "facenormalsepsilon", 1e-06 ...
                ), ...
                "scene", "scene1", ...
                "showlegend", false ...
            );
            if is_octave()
                expected.color = "rgb(33,144,141)";
            end
            tc.verifyEqual(p.data{1}, expected);
            try close(); catch; end
        end

